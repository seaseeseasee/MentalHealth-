export function getAssessment(id: string): Assessment | undefined {
  return ASSESSMENTS.find((a) => a.id === id);
}

export function optionsFor(a: Assessment, index: number): Option[] {
  return a.items[index].options ?? a.scale;
}

function topValue(opts: Option[]): number {
  return Math.max(...opts.map((o) => o.value));
}

export function maxScore(a: Assessment): number {
  return a.items.reduce((sum, _item, i) => sum + topValue(optionsFor(a, i)), 0);
}

export function bandsFor(a: Assessment, sex?: Sex | null): Band[] {
  if (a.bandsBySex) return a.bandsBySex[sex ?? 'male'];
  return a.bands ?? [];
}

/** Returns an error message when the answers do not fit the assessment, else null. */
export function validateAnswers(a: Assessment, answers: unknown, sex?: unknown): string | null {
  if (!Array.isArray(answers) || answers.length !== a.items.length) return 'จำนวนคำตอบไม่ครบ';
  for (let i = 0; i < answers.length; i++) {
    if (!optionsFor(a, i).some((o) => o.value === answers[i])) return `คำตอบข้อ ${i + 1} ไม่ถูกต้อง`;
  }
  if (a.askSex && sex !== 'male' && sex !== 'female') return 'กรุณาระบุเพศ';
  return null;
}

export function scoreAssessment(a: Assessment, answers: number[], sex?: Sex | null): ScoreResult {
  const points = answers.map((v, i) => (a.items[i].reverse ? topValue(optionsFor(a, i)) - v : v));
  const score = points.reduce((s, v) => s + v, 0);
  const bands = bandsFor(a, sex);
  const band = bands.find((b) => score >= b.min && score <= b.max) ?? bands[bands.length - 1];
  const crisis = a.crisisItem !== undefined && answers[a.crisisItem] > 0;
  const domains = (a.domains ?? []).map((d) => {
    let s = 0;
    let m = 0;
    a.items.forEach((item, i) => {
      if (item.domain === d.id) {
        s += points[i];
        m += topValue(optionsFor(a, i));
      }
    });
    return { id: d.id, label: d.label, score: s, max: m };
  });
  return { score, max: maxScore(a), band, crisis, domains };
}
