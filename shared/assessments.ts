// Assessment definitions and scoring, shared by the web app and the API.
// Only erasable TypeScript syntax is used so Node can run this file directly.

export type Level = 'good' | 'mild' | 'moderate' | 'severe';
export type CategoryId = 'mood' | 'strength' | 'life' | 'work';
export type Sex = 'male' | 'female';

export interface Option {
  label: string;
  value: number;
}

export interface Item {
  text: string;
  reverse?: boolean;
  options?: Option[];
  domain?: string;
}

export interface Band {
  min: number;
  max: number;
  level: Level;
  label: string;
  summary: string;
  advice: string[];
}

export interface Domain {
  id: string;
  label: string;
}

export interface Assessment {
  id: string;
  code: string;
  name: string;
  category: CategoryId;
  icon: string;
  minutes: number;
  status: 'standard' | 'draft';
  source: string;
  intro: string;
  prompt: string;
  scale: Option[];
  items: Item[];
  direction: 'higher-better' | 'lower-better';
  bands?: Band[];
  bandsBySex?: Record<Sex, Band[]>;
  askSex?: boolean;
  crisisItem?: number;
  domains?: Domain[];
}

export interface DomainScore {
  id: string;
  label: string;
  score: number;
  max: number;
}

export interface ScoreResult {
  score: number;
  max: number;
  band: Band;
  crisis: boolean;
  domains: DomainScore[];
}

